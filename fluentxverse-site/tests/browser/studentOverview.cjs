const { chromium, expect } = require(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.SITE_URL || 'http://127.0.0.1:5205';
const widths = (process.env.SITE_WIDTHS || '1920,1440,1024,900,768,390,320').split(',').map(Number);
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const output = process.env.SITE_SCREENSHOTS || '../output/screenshots/student-overview';
  await fs.mkdir(output,{recursive:true});
  try {
    for (const width of widths) {
      const context = await browser.newContext({ viewport:{width,height:950}, permissions:['clipboard-read','clipboard-write'] });
      const page = await context.newPage(), errors=[], protectedRequests=[];
      page.on('pageerror', error=>errors.push(error.message));
      await page.route(/https:\/\/(?:api|dashboard|student)\.fluentxverse\.com\//,route=>{protectedRequests.push(route.request().url());return route.abort();});
      await page.goto(base+'/');
      await expect(page.locator('.project-student .project-photo-link')).toHaveAttribute('href','/esl-student-app');
      await expect(page.locator('.project-student').getByRole('link',{name:'Open student app',exact:true})).toHaveAttribute('href','https://student.fluentxverse.com');
      await page.locator('.project-student').getByRole('link',{name:'How the student app works',exact:true}).click();
      await expect(page).toHaveURL(/\/esl-student-app$/);
      await expect(page).toHaveTitle('ESL Student App Guide | FluentXVerse');
      await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://fluentxverse.com/esl-student-app');
      await expect(page.getByRole('heading',{level:1})).toHaveText('ESL Student App');
      await expect(page.locator('.esl-reading > .esl-chapter')).toHaveCount(16);
      await expect(page.locator('.esl-public-scope')).toContainText('October 24, 2026');
      await expect(page.locator('.esl-tutor-portal')).toHaveAttribute('href','https://student.fluentxverse.com');
      await page.locator('.esl-guide-hero img').evaluate(image=>image.decode());
      await page.evaluate(()=>document.fonts.ready);
      await page.evaluate(()=>scrollTo(0,0));
      await page.screenshot({path:`${output}/${width}-intro.png`});
      const layout=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth+1,clipped:[...document.querySelectorAll('main h1,main h2,main h3,main p,main th,main td,nav a')].filter(element=>element.getBoundingClientRect().width&&element.scrollWidth>element.clientWidth+1).map(element=>element.textContent.slice(0,100))}));
      assert.equal(layout.overflow,false);assert.deepEqual(layout.clipped,[]);
      if(width<=900)await page.getByRole('button',{name:'In this guide',exact:true}).click();
      await page.getByRole('navigation',{name:'Platform overview chapters'}).getByRole('link',{name:/Find a tutor who fits/}).click();
      await expect(page).toHaveURL(/#find-a-tutor$/);
      await expect(page.locator('#find-a-tutor')).toBeFocused();
      assert(await page.locator('#find-a-tutor').evaluate(element=>element.getBoundingClientRect().top)>=70);
      await page.getByRole('button',{name:'Copy public guide link',exact:true}).click();
      assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),'https://fluentxverse.com/esl-student-app#find-a-tutor');
      await page.getByRole('group',{name:'Filter guide topics'}).getByRole('button',{name:'Privacy',exact:true}).click();
      await expect(page.locator('.esl-reading > .esl-chapter')).toHaveCount(2);
      const search=page.getByRole('searchbox',{name:'Search the platform overview'});
      await search.fill('not-a-real-topic');
      await expect(page.getByRole('heading',{name:'No matching chapters'})).toBeVisible();
      await page.locator('.esl-no-results').getByRole('button',{name:'Show full guide'}).click();
      await expect(page.locator('.esl-reading > .esl-chapter')).toHaveCount(16);
      await search.fill('error-correction');
      await expect(page.locator('.esl-reading > .esl-chapter')).toHaveCount(1);
      await expect(page.getByRole('heading',{name:'Preferences, lesson history, and follow-up'})).toBeVisible();
      await page.getByRole('button',{name:'Clear search',exact:true}).click();
      await page.addStyleTag({content:'.site-header,.skip-link{visibility:hidden!important}'});
      await page.locator('#lesson-access').screenshot({path:`${output}/${width}-access.png`});
      await page.locator('head style').last().evaluate(element=>element.remove());
      await page.emulateMedia({media:'print'});
      assert.equal(await page.locator('.esl-reading-toolbar').isVisible(),false);
      assert.equal(await page.locator('#learning-experience').isVisible(),true);
      await page.emulateMedia({media:'screen'});
      await page.locator('.esl-further-links').getByRole('link',{name:'The tutor-app and platform guide'}).click();
      await expect(page.getByRole('heading',{level:1})).toHaveText('FluentXVerse ESL');
      await expect(page.locator('.esl-public-scope')).toContainText('October 13, 2026');
      await expect(page.locator('.esl-tutor-portal')).toHaveAttribute('href','https://tutor.fluentxverse.com');
      await page.locator('.esl-further-links').getByRole('link',{name:'The student-app guide'}).click();
      await expect(page.getByRole('heading',{level:1})).toHaveText('ESL Student App');
      await expect(search).toHaveValue('');
      await page.goto(base+'/esl-student-app#consent-and-privacy');
      await expect(page.locator('#consent-and-privacy')).toBeFocused();
      await page.reload();
      await expect(page.getByRole('heading',{name:'Your lesson is not public content'})).toBeVisible();
      await expect(page.locator('.site-footer').getByRole('link',{name:'Student-app guide'})).toHaveAttribute('href','/esl-student-app');
      assert.deepEqual(protectedRequests,[]);assert.deepEqual(errors,[]);
      await context.close();
      console.log(`PASS student guide ${width}: public discovery, source/date, search/topics, deep links, copy, print, cross-guide navigation, no protected requests`);
    }
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
