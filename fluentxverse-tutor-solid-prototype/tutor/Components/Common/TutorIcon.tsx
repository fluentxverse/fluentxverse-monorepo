const brands: Record<string, string> = { 'fa-twitter': 'X', 'fa-facebook-f': 'f', 'fa-linkedin-in': 'in', 'fa-youtube': 'YT', 'fa-apple': 'Apple', 'fa-windows': 'Windows', 'fa-linux': 'Linux' };
// String-based tutor catalogs and status helpers share the same control icons.
export default function TutorIcon(_props0: {
    name?: string;
    size?: number;
    className?: string;
} & LucideProps) {
    const props = splitProps(_props0, ["name", "size", "className", "style"])[1];
    return createMemo(() => {
        if ((_props0["name"] === undefined ? '' : _props0["name"]).startsWith('metrics-dot'))
            return <span class={_props0["name"] === undefined ? '' : _props0["name"]} aria-hidden="true"/>;
        const tokens = createMemo(() => (_props0["name"] === undefined ? '' : _props0["name"]).split(/\s+/));
        const key = createMemo(() => tokens().find(token => token in icons || token in brands));
        const extras = createMemo(() => tokens().filter(token => !/^(fa[bs]?|fi|ri|fa-|fi-sr-|ri-)/.test(token)).join(' '));
        const classes = createMemo(() => `tutor-icon ${extras()} ${_props0["className"] === undefined ? '' : _props0["className"]}${tokens().some(token => /(?:fa|ri)-spin/.test(token)) ? ' tutor-icon-spin' : ''}`);
        if (key() && brands[key()])
            return <span class={classes()} aria-hidden="true">{brands[key()]}</span>;
        const Icon = createMemo(() => icons[key() as keyof typeof icons] || CircleHelp);
        const styledSize = createMemo(() => _props0["style"] && typeof _props0["style"] === 'object' && 'fontSize' in _props0["style"] ? parseFloat(String(_props0["style"].fontSize)) : 18);
        return <Dynamic component={Icon()} {...props} data-icon={_props0["name"] === undefined ? '' : _props0["name"]} class={classes()} size={_props0["size"] ?? styledSize()} style={cssStyle(_props0["style"])} aria-hidden="true"/>;
    }) as unknown as JSX.Element;
}
