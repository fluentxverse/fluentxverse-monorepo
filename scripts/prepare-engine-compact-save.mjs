import { cpSync, copyFileSync, mkdirSync, readFileSync, readdirSync, symlinkSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
const root=process.cwd(),prior=join(root,'output/release/proof-destinations-20261025/frontend');
const release=join(root,'output/release/engine-compact-save-20261025/frontend');
mkdirSync(release,{recursive:true});
for(const dir of ['gmr-dashboard','public','src'])cpSync(join(prior,dir),join(release,dir),{recursive:true});
symlinkSync(join(root,'../budol/node_modules'),join(release,'node_modules'));
const hash=buffer=>createHash('sha256').update(buffer).digest('hex');
const html=await(await fetch('https://engine.fluentxverse.com/')).text();
const asset=html.match(/src="(\/index-[^" ]+\.js)"/)?.[1];
if(asset!=='/index-j7j89a7j.js')throw Error('Live frontend changed');
const live=Buffer.from(await(await fetch('https://engine.fluentxverse.com'+asset)).arrayBuffer());
const build=out=>execFileSync('bun',['build','./gmr-dashboard/index.html','--outdir='+out,'--public-path=/','--production','--minify'],{cwd:release,stdio:'inherit'});
build('baseline-dist');
const baseline=readdirSync(join(release,'baseline-dist')).find(f=>f.endsWith('.js'));
if(hash(readFileSync(join(release,'baseline-dist',baseline)))!==hash(live))throw Error('Baseline source differs from deployed frontend');
copyFileSync(join(root,'../budol/gmr-dashboard/src/ProofDestinationPanel.tsx'),join(release,'gmr-dashboard/src/ProofDestinationPanel.tsx'));
const cssPath=join(release,'gmr-dashboard/src/operations.css');
const currentCSS=readFileSync(join(root,'../budol/gmr-dashboard/src/operations.css'),'utf8');
const rules=currentCSS.split('\n').filter(line=>line.startsWith('.proof-destination-controls')).join('\n');
if(rules.split('\n').length!==3)throw Error('Compact layout rules changed');
writeFileSync(cssPath,readFileSync(cssPath,'utf8')+'\n'+rules+'\n');
build('dist');
for(const path of ['_headers','public/client-env.js']){mkdirSync(join(release,'dist',path,'..'),{recursive:true});copyFileSync(join(prior,'dist',path),join(release,'dist',path));}
let nextHTML=readFileSync(join(release,'dist/index.html'),'utf8').replaceAll('href="./','href="/').replaceAll('src="./','src="/');
if(!nextHTML.includes('<script src="/public/client-env.js"></script>'))nextHTML=nextHTML.replace('</head>','<script src="/public/client-env.js"></script>\n</head>');
writeFileSync(join(release,'dist/index.html'),nextHTML);
for(const file of ['worker.ts','wrangler.json'])copyFileSync(join(prior,file),join(release,file));
writeFileSync(join(release,'manifest.json'),JSON.stringify({preparedAt:new Date().toISOString(),previousAsset:asset,baselineMatched:true,backendChanged:false,changes:['40px icon-only save button with tooltip','Dropdown-adjacent alignment at desktop and mobile']},null,2));
console.log('PASS scoped compact-save frontend ready');
