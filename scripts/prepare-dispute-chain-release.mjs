import { cpSync, mkdirSync, existsSync, writeFileSync, readFileSync, symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const revision=process.argv.includes('--revision')?process.argv[process.argv.indexOf('--revision')+1]:'';
if(revision && revision!=='r2')throw Error('Unknown release revision');
const id='dispute-sync-20261102'+(revision?'-'+revision:'');
const baseline=revision?'dispute-sync-20261102':'lesson-disputes-shared-roles-20261102';
const root=process.cwd(), release=join(root,'output/release',id);
const stage='/tmp/fxv-dispute-sync/gmr-engine';
if(existsSync(join(release,'prepared.json')))throw Error('Release already prepared; do not overwrite');
const source=join(release,'engine-source');
mkdirSync(source,{recursive:true});
const copy=(from,to)=>{mkdirSync(join(to,'..'),{recursive:true});cpSync(from,to,{recursive:true});};
copy(join(root,'output/release',baseline,'engine-source'),source);
for(const file of ['cmd/api/main.go','cmd/dispute-pilot','internal/disputes','internal/store/dispute_sync.go','internal/store/dispute_sync_integration_test.go','scripts/dispute-sync.ts','scripts/dispute-sync.e2e.ts','scripts/dispute-pilot.ts','scripts/vault-account.ts'])copy(join(stage,file),join(source,file));
if(!existsSync(join(source,'node_modules')))symlinkSync('/home/paulanthonyarriola/Desktop/budol/gmr-engine/node_modules',join(source,'node_modules'));
const run=(cmd,args,cwd=source)=>execFileSync(cmd,args,{cwd,stdio:'inherit',env:{...process.env,CGO_ENABLED:'0',GOCACHE:'/tmp/fxv-engine-go-cache'}});
run('go',['test','./internal/...','./cmd/...']);
run('bunx',['tsc','--noEmit','--target','esnext','--module','esnext','--moduleResolution','bundler','--resolveJsonModule','--skipLibCheck','--strict','--types','bun','scripts/dispute-sync.ts','scripts/dispute-sync.e2e.ts','scripts/dispute-pilot.ts']);
const image=join(release,'engine');mkdirSync(join(image,'scripts'),{recursive:true});
for(const [cmd,name] of [['api','gmr-engine'],['dispute-pilot','dispute-pilot']])run('go',['build','-buildvcs=false','-trimpath','-ldflags=-s -w','-o',join(image,name),'./cmd/'+cmd]);
for(const file of ['dispute-sync.ts','dispute-pilot.ts','vault-account.ts'])copy(join(source,'scripts',file),join(image,'scripts',file));
writeFileSync(join(image,'Dockerfile'),'FROM fluentxverse-cloud/gmr-engine:'+baseline+'\nCOPY gmr-engine dispute-pilot /usr/local/bin/\nCOPY scripts/ /app/scripts/\n');
run('tar',['-czf',join(release,'engine.tar.gz'),'-C',image,'.'],root);
const pilot=join(release,'pilot');mkdirSync(join(pilot,'scripts'),{recursive:true});
copy(join(image,'dispute-pilot'),join(pilot,'dispute-pilot'));
for(const file of ['dispute-sync.ts','dispute-pilot.ts','vault-account.ts'])copy(join(image,'scripts',file),join(pilot,'scripts',file));
run('tar',['-czf',join(release,'pilot.tar.gz'),'-C',pilot,'.'],root);
const sha=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
writeFileSync(join(release,'prepared.json'),JSON.stringify({id,image:'fluentxverse-cloud/gmr-engine:'+id,baseline:'fluentxverse-cloud/gmr-engine:'+baseline,binarySHA256:sha(join(image,'gmr-engine')),pilotSHA256:sha(join(image,'dispute-pilot')),mainnetWritesEnabled:false},null,2));
console.log('Prepared dispute synchronization release and Sepolia-only pilot runner. Not activated.');
